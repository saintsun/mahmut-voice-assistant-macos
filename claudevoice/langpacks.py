def available() -> list[dict]:
    return [{"code": k, "label": v["label"]} for k, v in PACKS.items()]


def build(code: str, name: str) -> dict | None:
    """Pakedi cagri adiyla doldurup dondurur."""
    pack = PACKS.get(code)
    if pack is None:
        return None
    out = {k: v for k, v in pack.items() if k != "phrases"}
    out["phrases"] = {k: [p.format(name=name) for p in v]
                      for k, v in pack["phrases"].items()}
    return out
